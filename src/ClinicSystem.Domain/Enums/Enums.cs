// ══════════════════════════════════════════════════════════════
// این فایل مثل یه دیکشنری از "وضعیت‌ها" و "نوع‌ها" هست
// هر کدوم از این‌ها یه لیست از حالت‌های ممکن رو تعریف می‌کنن
// مثلاً نوبت می‌تونه "در انتظار" یا "تأیید شده" یا "لغو شده" باشه
// ══════════════════════════════════════════════════════════════
namespace ClinicSystem.Domain.Enums;

// ─── وضعیت نوبت ───────────────────────────────────────────────
// این enum نشون می‌ده که یه نوبت الان در چه مرحله‌ای هست
public enum AppointmentStatus
{
    Pending = 1,    // در انتظار — نوبت ثبت شده ولی هنوز تأیید نشده
    Confirmed = 2,  // تأیید شده — منشی یا دکتر تأییدش کرده
    Cancelled = 3,  // لغو شده — نوبت کنسل شده
    Completed = 4,  // انجام شده — بیمار ویزیت شده و تموم شده
    NoShow = 5      // نیامد — بیمار سر وقت نیومد
}

// ─── نوع نوبت ─────────────────────────────────────────────────
// نوبت یا حضوری هست یا آنلاین (ویزیت اینترنتی)
public enum AppointmentType
{
    InPerson = 1,  // حضوری — بیمار خودش میاد مطب
    Online = 2     // آنلاین — از طریق اینترنت ویزیت می‌شه
}

// ─── جنسیت ────────────────────────────────────────────────────
// جنسیت بیمار رو نگه می‌داره
public enum Gender
{
    Male = 1,   // مرد
    Female = 2, // زن
    Other = 3   // سایر
}

// ─── نقش کاربر ────────────────────────────────────────────────
// هر کسی که وارد سیستم میشه یه "نقش" داره که مشخص می‌کنه چه کارایی می‌تونه بکنه
public enum UserRole
{
    SuperAdmin = 1, // دکتر / صاحب کلینیک — به همه چیز دسترسی داره
    Admin = 2,      // منشی — می‌تونه نوبت بده و بیمار اضافه کنه
    Patient = 3     // بیمار — فقط اطلاعات خودش رو می‌بینه
}

// ─── نوع اعلان/پیام ───────────────────────────────────────────
// سیستم می‌تونه از چند روش مختلف به بیمار خبر بده
public enum NotificationType
{
    SMS = 1,      // پیامک — پیام کوتاه به گوشی
    Telegram = 2, // تلگرام — پیام در تلگرام
    WhatsApp = 3, // واتساپ — پیام در واتساپ
    InApp = 4     // داخل برنامه — پیام در خود سایت/اپ
}

// ─── وضعیت اعلان ──────────────────────────────────────────────
// هر پیامی که فرستاده میشه یه وضعیت داره
public enum NotificationStatus
{
    Pending = 1, // در صف ارسال — هنوز فرستاده نشده
    Sent = 2,    // فرستاده شد — با موفقیت رسید
    Failed = 3   // خطا — ارسال ناموفق بود
}

// ─── وضعیت مشاوره آنلاین ──────────────────────────────────────
// مشاوره آنلاین (چت با دکتر) مراحل مختلفی داره
public enum ConsultationStatus
{
    Waiting = 1,    // در انتظار — بیمار سوال پرسیده، دکتر هنوز جواب نداده
    InProgress = 2, // در حال انجام — دکتر داره جواب می‌ده
    Completed = 3,  // تموم شد — مشاوره کامل شد
    Cancelled = 4   // لغو شد — مشاوره کنسل شد
}

// ─── وضعیت نسخه ───────────────────────────────────────────────
// نسخه‌های پزشکی هم یه وضعیت دارن
public enum PrescriptionStatus
{
    Active = 1,    // فعال — نسخه هنوز معتبره و می‌شه باهاش دارو گرفت
    Expired = 2,   // منقضی — تاریخ نسخه گذشته
    Cancelled = 3  // لغو شده — دکتر نسخه رو کنسل کرده
}

// ─── نوع علائم حیاتی ──────────────────────────────────────────
// این enum مشخص می‌کنه که کدوم اندازه‌گیری بدن بیمار ثبت شده
// مثلاً وزن، فشار خون، قند خون و...
public enum VitalTrendType
{
    Weight = 1,                 // وزن — به کیلوگرم
    BloodPressureSystolic = 2,  // فشار خون سیستولیک — عدد بالایی فشار (مثل ۱۲۰)
    BloodPressureDiastolic = 3, // فشار خون دیاستولیک — عدد پایینی فشار (مثل ۸۰)
    BloodSugar = 4,             // قند خون — میزان شکر در خون
    HeartRate = 5,              // ضربان قلب — چند بار در دقیقه قلب می‌زنه
    Temperature = 6,            // دمای بدن — تب داره یا نه
    OxygenSaturation = 7,       // اشباع اکسیژن — درصد اکسیژن خون (باید بالای ۹۵ باشه)
    BMI = 8                     // شاخص توده بدنی — نسبت وزن به قد (اضافه وزن داره یا نه)
}

