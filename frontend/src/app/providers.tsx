"use client";

// ══════════════════════════════════════════════════════════════
// فایل Providers — پوشش‌دهنده کل برنامه
//
// این فایل مثل یه "لایه رویی" هست که دور همه صفحه‌های برنامه
// می‌پیچه. کارهایی که اینجا انجام میشه:
// ۱. وقتی زبان عوض میشه، جهت صفحه رو هم عوض می‌کنه (RTL/LTR)
// ۲. سیستم نوتیفیکیشن (toast) رو راه‌اندازی می‌کنه — همون
//    پیغام‌های کوچیکی که گوشه صفحه ظاهر میشن
// ══════════════════════════════════════════════════════════════

// Toaster = کتابخونه‌ای که پیغام‌های موفقیت/خطا رو نشون میده
import { Toaster } from "react-hot-toast";

// useAppStore = استور زبان و تنظیمات برنامه
import { useAppStore } from "@/store/useStore";

// useEffect = وقتی یه چیزی تغییر می‌کنه، این کد اجرا میشه
import { useEffect } from "react";

// ──────────────────────────────────────────────────────────────
// Providers: یه کامپوننت که دور کل children (محتوای برنامه)
// می‌پیچه و تنظیمات کلی رو اعمال می‌کنه
// ──────────────────────────────────────────────────────────────
export function Providers({ children }: { children: React.ReactNode }) {

  // lang = زبان فعلی برنامه: "fa" برای فارسی، "en" برای انگلیسی
  const { lang } = useAppStore();

  // ── جهت صفحه ─────────────────────────────────────────────
  // هر بار که lang عوض میشه، این کد اجرا میشه
  useEffect(() => {
    const html = document.documentElement; // تگ <html> صفحه رو میگیره

    // اگه فارسیه → dir="rtl" (راست به چپ)
    // اگه انگلیسیه → dir="ltr" (چپ به راست)
    html.dir = lang === "fa" ? "rtl" : "ltr";

    // زبان رو هم برای accessibility تنظیم می‌کنه
    html.lang = lang;
  }, [lang]); // ← فقط وقتی lang عوض میشه اجرا میشه

  // ── ثبت سرویس‌ورکر برای نصب‌پذیری PWA ──────────────────────
  // فقط یه‌بار (mount اول) لازمه؛ مرورگرهایی که سرویس‌ورکر رو
  // پشتیبانی نمی‌کنن (خیلی نادره) بی‌سروصدا رد میشن — بدون این
  // هم سایت عادی کار می‌کنه، فقط دکمه «نصب» ظاهر نمیشه
  useEffect(() => {
    if ("serviceWorker" in navigator) {
      navigator.serviceWorker.register("/sw.js").catch(() => {});
    }
  }, []);

  return (
    <>
      {/* children = همه صفحه‌های برنامه اینجا رندر میشن */}
      {children}

      {/* ── سیستم نوتیفیکیشن (Toast) ──────────────────────
          Toast یعنی پیغام کوچیکی که میاد و چند ثانیه بعد
          خودش میره — مثلاً "ذخیره شد" یا "خطا در ارتباط"

          position: اگه فارسیه → بالا-چپ (چون RTL هست)
                    اگه انگلیسیه → بالا-راست
          duration: ۴۰۰۰ میلی‌ثانیه = ۴ ثانیه نشون میده
          font-vazir: فونت فارسی برای نوشته‌های توست
      ────────────────────────────────────────────────── */}
      <Toaster
        position={lang === "fa" ? "top-left" : "top-right"}
        toastOptions={{
          className: "font-vazir",
          duration: 4000,
          style: { fontFamily: "var(--font-vazir), sans-serif" },
        }}
      />
    </>
  );
}
