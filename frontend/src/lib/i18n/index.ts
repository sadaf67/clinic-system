// ══════════════════════════════════════════════════════════════
// این فایل "مرکز ترجمه‌ها" هست
//
// برنامه دو زبان داره: فارسی (fa) و انگلیسی (en)
// هر متنی که روی صفحه نشون داده میشه از اینجا می‌آد
//
// useTranslations = یه تابع که بهش بگی زبانت چیه، بهت متن‌های درست میده
// مثلاً: useTranslations("fa") → همه متن‌ها فارسی میشن
// ══════════════════════════════════════════════════════════════
import { fa } from "./fa"; // همه متن‌های فارسی
import { en } from "./en"; // همه متن‌های انگلیسی

// Lang = فقط دو مقدار مجاز: "fa" یا "en"
export type Lang = "fa" | "en";

// Translations = شکل آبجکت ترجمه‌ها (مثل fa.ts)
export type Translations = typeof fa;

// جدولی که هر زبان رو به فایل ترجمه‌اش وصل می‌کنه
const translations: Record<Lang, Translations> = { fa, en };

// ─── تابع اصلی ───────────────────────────────────────────────
// این تابع رو در هر صفحه صدا می‌زنیم تا متن‌های زبان درست رو بگیریم
// مثلاً: const t = useTranslations("fa")
// بعدش: t.auth.loginTitle → "ورود به سیستم"
export function useTranslations(lang: Lang): Translations {
  return translations[lang]; // بسته به زبان، فایل درست رو برمیگردونه
}

// اگه جایی خواستن مستقیم به آبجکت فارسی یا انگلیسی دسترسی داشته باشن
export { fa, en };
